"""Write the final-run configs (configs/*.yaml) from the spatial-exp d4rt_ctxvs line.

    python xsy_utils/final_runs/gen_configs.py

Every run = ``spatial-exp/configs/robotwin_clean_d4rt_ctxvs.yaml`` (the existing d4rt-q08-ctxvs
recipe: official robotwin.yaml + MoGe/MoRGBD/DINO-video alignment + d4rt probe, context
visual_state) with PPU-side paths, and only these changes:

    res2   data.img_size 384, opencv_lanczos4, preserve_image_resolution, 12x12 student grid
           (qianlei's full432 input; xsy_utils/resolution_exp/README.md)
    augon  data.image_augment + configs/vla/robotwin/full432_augmentation_recipe.yaml
           (qianlei's full432 observation augmentation; FULL432_AUGMENTATION.md)
    q96    d4rt_params.num_queries 96
    res1 + augon   the same augmentation on the default 256 bilinear input (the augmenter's input guard
           accepts both layouts, lingbotvla/data/vla_data/utils.py)

train.global_batch_size is the run's batch (train.sh default GBS): 256, except the 4-node res1 aug-on run at the
official 1024 (32 GPUs, no grad accumulation). Steps / compile / checkpointing are set by train.sh (20k steps,
compile off); the yaml carries the same values for reference.
"""
import copy
import pathlib
import sys
from dataclasses import asdict

import yaml

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO))
from lingbotvla.utils.observation_augmentation import parse_config  # noqa: E402

CKPT = "/mnt/cpfs/legacy_lingbot/checkpoints"
# copy of H20 /2025233210/xiesy/data/lingbot_robotwin_clean_d4rt on the team CPFS (not on the personal 2 TB quota).
# NOT /mnt/oss: under 8 ranks x 12 loader workers the ossfs mount of a DLC node died (README section 1).
D4RT_ROOT = "/mnt/cpfs_shared/lingbot-data/lingbot_robotwin_clean_d4rt"
BASE = REPO / "xsy_utils/spatial-exp/configs/robotwin_clean_d4rt_ctxvs.yaml"
RECIPE = REPO / "configs/vla/robotwin/full432_augmentation_recipe.yaml"

RUNS = {
    "d4rt_q08_ctxvs_res1_augoff": dict(res2=False, aug=False, queries=8),
    "d4rt_q08_ctxvs_res2_augoff": dict(res2=True, aug=False, queries=8),
    "d4rt_q08_ctxvs_res2_augon": dict(res2=True, aug=True, queries=8),
    "d4rt_q96_ctxvs_res2_augoff": dict(res2=True, aug=False, queries=96),
    "d4rt_q96_ctxvs_res2_augon": dict(res2=True, aug=True, queries=96),
    "d4rt_q96_ctxvs_res1_augon": dict(res2=False, aug=True, queries=96, gbs=1024),  # 4 nodes x 8 PPU
}


def base_config() -> dict:
    cfg = yaml.safe_load(BASE.read_text())
    m, d, t = cfg["model"], cfg["data"], cfg["train"]
    m["model_path"] = f"{CKPT}/lingbot-vla-v2-6b"
    m["tokenizer_path"] = f"{CKPT}/Qwen3-VL-4B-Instruct"
    # relative to the repo root (train.sh runs from there)
    d["train_path"] = "xsy_utils/configs/ppu/robotwin_clean50.txt"
    d["robot_config_root"] = "xsy_utils/configs/ppu/robot_configs"
    a = t["align_params"]
    a["depth"]["moge_path"] = f"{CKPT}/moge-2-vitb-normal/model.pt"
    a["depth"]["morgbd_path"] = f"{CKPT}/lingbot-vla-v2-6b/depth/model.pt"
    a["video"]["ckpt_path"] = f"{CKPT}/lingbot-vla-v2-6b/dino_video/teacher_step_10000.pth"
    a["video"]["config_path"] = f"{CKPT}/lingbot-vla-v2-6b/dino_video/config.yaml"
    t["d4rt_params"]["root"] = D4RT_ROOT
    t["output_dir"] = "/set/by/train.sh"
    t["use_compile"] = False
    t["max_steps"], t["save_steps"] = 20000, 2500  # = train.sh defaults
    for key in ("model_path", "tokenizer_path"):
        assert "/2025233210" not in m[key]
    return cfg


def make(res2: bool, aug: bool, queries: int, gbs: int = 256) -> dict:
    cfg = copy.deepcopy(base_config())
    d, t = cfg["data"], cfg["train"]
    t["global_batch_size"] = gbs
    if res2:
        d.update(img_size=384, image_resize_mode="opencv_lanczos4", preserve_image_resolution=True, roi_config={})
        t["align_params"]["llm"]["image_token_size"] = 12
    d["image_augment"] = aug
    if aug:
        d["image_augmentation_config"] = asdict(parse_config(yaml.safe_load(RECIPE.read_text())))
    t["d4rt_params"]["num_queries"] = queries
    return cfg


def main() -> None:
    out = HERE / "configs"
    out.mkdir(exist_ok=True)
    for name, spec in RUNS.items():
        cfg = make(**spec)
        text = yaml.safe_dump(cfg, sort_keys=False)
        assert "/2025233210" not in text, name
        header = (f"# {name}: generated by xsy_utils/final_runs/gen_configs.py from "
                  f"spatial-exp/configs/robotwin_clean_d4rt_ctxvs.yaml -- edit the generator, not this file.\n")
        (out / f"{name}.yaml").write_text(header + text)
        print("wrote", out / f"{name}.yaml")


if __name__ == "__main__":
    main()
